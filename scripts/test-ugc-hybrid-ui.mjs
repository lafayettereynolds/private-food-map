// Reproducible isolated UI test; never connects to a Taste Map API or device.
import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.UGC_BROWSER_CHANNEL ? { channel: process.env.UGC_BROWSER_CHANNEL } : {}) })
const page = await browser.newPage({ viewport: { width: 420, height: 900 } })
const origin = process.env.UGC_TEST_ORIGIN || 'http://127.0.0.1:5197'
await page.route('**/*', route => route.request().url().startsWith(origin) ? route.continue() : route.abort())
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(`${origin}/tests/ugc/browser-harness.html`)
  await page.getByTestId('photo-target').filter({ hasText: 'visit-fallback' }).waitFor()
  await page.getByRole('button', { name: '内容更多操作' }).first().click()
  await page.getByRole('button', { name: '举报', exact: true }).click()
  await page.getByLabel('举报原因').selectOption('harassment')
  await page.getByRole('button', { name: '提交举报' }).click()
  await page.getByText('举报已收到，将按社区规则审核。').waitFor()
  await page.getByRole('button', { name: 'Toggle failure' }).click()
  await page.getByRole('button', { name: '内容更多操作' }).first().click()
  await page.getByRole('button', { name: '举报', exact: true }).click()
  await page.getByRole('button', { name: '提交举报' }).click()
  await page.getByRole('alert').filter({ hasText: '测试：服务端拒绝' }).waitFor()
  await page.getByRole('button', { name: 'Switch account' }).evaluate(button => button.click())
  await page.getByRole('button', { name: '内容更多操作' }).nth(1).click()
  await page.getByRole('button', { name: '删除评论', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '举报', exact: true }).count(), 0)
  await page.getByRole('button', { name: '确认', exact: true }).click()
  assert.equal(await page.getByText('own 评论正文', { exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Finish delete' }).evaluate(button => button.click())
  await page.getByText('own 评论正文', { exact: true }).waitFor()
  await page.getByRole('alert').filter({ hasText: '测试：删除失败' }).waitFor()
  await page.getByRole('button', { name: 'Toggle failure' }).evaluate(button => button.click())
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await page.getByRole('button', { name: 'Finish delete' }).evaluate(button => button.click())
  await page.getByText('评论已删除。', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Rerender' }).click()
  assert.equal(await page.getByText('own 评论正文', { exact: true }).count(), 0)
  await page.getByRole('button', { name: '内容更多操作' }).last().click()
  assert.equal(await page.getByRole('button', { name: '删除评论', exact: true }).count(), 0)
  await page.getByRole('button', { name: '屏蔽此用户', exact: true }).click()
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await page.getByText('other 评论正文', { exact: true }).waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: 'Switch account' }).click()
  await page.getByText('other 评论正文', { exact: true }).waitFor()
  await page.getByText('own 评论正文', { exact: true }).waitFor()
  await page.getByRole('button', { name: '内容更多操作' }).nth(1).click()
  await page.getByRole('button', { name: '删除评论', exact: true }).click()
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await page.getByRole('button', { name: 'Switch account' }).evaluate(button => button.click())
  await page.getByRole('button', { name: 'Finish delete' }).click()
  await page.getByText('own 评论正文', { exact: true }).waitFor()
  assert.equal(await page.getByText('评论已删除。', { exact: true }).count(), 0)
  await page.screenshot({ path: '.private/ugc-validation/hybrid-ugc-actions.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('UGC shared Hybrid UI: report success/error, owner-only delete, optimistic hide/rollback, tombstone rerender, block filter, A→B→A reset and late-result fence PASS')
} finally { await browser.close() }
