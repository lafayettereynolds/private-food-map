import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const source = (name: string) => readFileSync(new URL(name, import.meta.url), 'utf8')

describe('Phase 2B Hybrid Map product contract', () => {
  it('keeps one centered title switch and the exact three canonical scopes', () => {
    const page = source('../../src/components/MyMapBrowsePage.tsx')
    expect(page).toContain('HYBRID_MAP_PRIMARY_SCOPES.map')
    expect(page).toContain("切换到我的列表")
    expect(page).toContain("切换到我的地图")
    expect(page).not.toContain('适合你')
    expect(page).not.toMatch(/segmented/i)
  })

  it('uses the Web provider only in Browser and the established Native MapKit surface on iOS', () => {
    const page = source('../../src/components/MyMapBrowsePage.tsx')
    const browserSurface = source('../../src/components/BrowserMapSurface.tsx')
    const nativeSurface = source('../../src/components/NativeMapSurface.tsx')
    const browserApp = source('../../src/App.tsx')
    const hybridShell = source('../../src/hybrid/app/HybridAppShell.tsx')
    const mapKitHost = source('../../ios/TasteMap/TasteMap/Hybrid/TasteMapHybridMapSurface.swift')
    expect(page).toContain('MapSurface: ComponentType<MyMapSurfaceProps>')
    expect(page).toContain('<MapSurface')
    expect(page).not.toContain("from './MapView'")
    expect(page).not.toContain("from './NativeMapSurface'")
    expect(browserSurface).toContain("import { MapView } from './MapView'")
    expect(browserApp).toContain('MapSurface={BrowserMapSurface}')
    expect(hybridShell).toContain('MapSurface={NativeMapSurface}')
    expect(hybridShell).not.toContain('BrowserMapSurface')
    expect(nativeSurface).toContain("data-map-engine=\"native-mapkit\"")
    expect(mapKitHost).toContain('RestaurantMapView(')
    expect(mapKitHost).not.toContain('MKMapView(')
  })

  it('keeps Map mounted while Hybrid Restaurant Detail owns the visible route', () => {
    const shell = source('../../src/hybrid/app/HybridAppShell.tsx')
    const nativeSurface = source('../../src/components/NativeMapSurface.tsx')
    const nativeHost = source('../../ios/TasteMap/TasteMap/Hybrid/TasteMapHybridMapSurface.swift')
    const nativeRuntime = source('../../ios/TasteMap/TasteMap/Hybrid/TasteMapHybridRuntime.swift')
    expect(shell).toContain('mapWasActivated ? <MyMapBrowsePage')
    expect(shell).toContain("active={route.surface === 'map'}")
    expect(shell).toContain("navigate({ surface: 'restaurant', id: restaurantID })")
    expect(nativeSurface).toContain('markers: active ? restaurants.map')
    expect(nativeHost).toContain('guard request.visible else')
    expect(nativeHost).not.toContain('model.update(request, resources: resources)\n            return')
    expect(nativeRuntime).toContain('if !request.visible')
  })

  it('keeps real AMap interaction evidence for Browser without making it an iOS credential gate', () => {
    const map = source('../../src/components/MapView.tsx')
    const nativeSurface = source('../../src/components/NativeMapSurface.tsx')
    const contracts = source('../../src/platform/TasteMapPlatform.ts')
    expect(map).toContain("data-map-runtime={mapReady ? 'amap-ready' : 'amap-loading'}")
    expect(map).toContain('data-map-runtime="fallback-static"')
    expect(map).toContain('静态餐厅位置预览，不支持地图平移或缩放')
    expect(map).toContain("map.on('moveend', publishViewport)")
    expect(map).toContain("map.on('zoomend', publishViewport)")
    expect(map).toContain('bounds = map.getBounds()')
    expect(map).toContain('center = map.getCenter()')
    expect(map).toContain('zoom: map.getZoom()')
    expect(nativeSurface).toContain('platform.map.updateNativeSurface')
    expect(contracts).toContain("'map.surface.update'")
  })

  it('preserves Native gesture/viewport/selection and React control ownership contracts', () => {
    const mapKit = source('../../ios/TasteMap/TasteMap/Features/Map/ClusteredRestaurantMapView.swift')
    const host = source('../../ios/TasteMap/TasteMap/Hybrid/TasteMapHybridMapSurface.swift')
    const page = source('../../src/components/MyMapBrowsePage.tsx')
    const pageCSS = source('../../src/components/myMapBrowsePage.css')
    expect(mapKit).toContain('mapView.isZoomEnabled = true')
    expect(mapKit).toContain('mapView.isScrollEnabled = true')
    expect(mapKit).toContain('mapView.isRotateEnabled = true')
    expect(mapKit).toContain('regionDidChangeAnimated')
    expect(mapKit).toContain('didSelect view: MKAnnotationView')
    expect(host).toContain('reactControlExclusions')
    expect(host).toContain('point(inside point: CGPoint')
    expect(page).toContain("event.name === 'map.viewport.changed'")
    expect(page).toContain("event.name === 'map.restaurant.selected'")
    expect(pageCSS).toContain('--tm-map-header-safe-top')
    expect(pageCSS).toContain('inset: calc(151px + var(--tm-map-header-safe-top))')
  })

  it('keeps missing GPS quiet on the shared Map surface', () => {
    const page = source('../../src/components/MyMapBrowsePage.tsx')
    expect(page).toContain('Missing or denied GPS is a quiet capability state')
    expect(page).toMatch(/\.catch\(\(\) => \{[\s\S]*?setLocationMessage\(null\)/)
    expect(page).not.toContain('定位权限未开启；餐厅数据仍可浏览')
    expect(page).not.toContain('暂时无法取得新鲜位置；未使用城市中心或地图中心代替')
    expect(page).toContain("location.accuracyMode === 'reduced'")
  })

  it('opens full Restaurant Detail from one marker tap without an intermediate preview card', () => {
    const page = source('../../src/components/MyMapBrowsePage.tsx')
    const nativeSurface = source('../../src/components/NativeMapSurface.tsx')
    const shell = source('../../src/hybrid/app/HybridAppShell.tsx')
    const bridge = source('../../ios/TasteMap/TasteMap/Hybrid/TasteMapHybridBridgeService.swift')
    expect(page).toContain('onSelect={openRestaurant}')
    expect(page).toContain('if (restaurant) openRestaurant(restaurant, false)')
    expect(page).toContain('onOpenRestaurant(restaurant.id)')
    expect(page).not.toContain('className="tm-map-selection"')
    expect(page).not.toContain('>查看详情</button>')
    expect(nativeSurface).not.toContain("'.tm-map-selection'")
    expect(shell).toContain('isLocalNavigationEcho')
    expect(bridge).toContain('ownedDetail(try ownedRestaurantDTO(restaurant))')
    expect(bridge).not.toContain('let scoped = try scopedRestaurants()')
  })

  it('uses the same evidence-based food emoji fallback in Browser and Native MapKit markers', () => {
    const browserMap = source('../../src/components/MapView.tsx')
    const nativeSurface = source('../../src/components/NativeMapSurface.tsx')
    const nativeMap = source('../../ios/TasteMap/TasteMap/Hybrid/TasteMapHybridMapSurface.swift')
    expect(browserMap).toContain('resolveRestaurantFoodEmoji(restaurant, restaurant.markerEmoji)')
    expect(nativeSurface).toContain('fallbackEmoji: resolveRestaurantFoodEmoji(restaurant, restaurant.markerEmoji)')
    expect(nativeMap).toContain('fallbackEmoji: value.fallbackEmoji')
    expect(nativeMap).toContain('RestaurantMapMarkerVisual.emoji')
  })

  it('keeps Restaurant score rings clean and independent from the active scope status', () => {
    const browserMap = source('../../src/components/MapView.tsx')
    const browserCSS = source('../../src/styles/global.css')
    const nativeMap = source('../../ios/TasteMap/TasteMap/Features/Map/ClusteredRestaurantMapView.swift')
    expect(browserMap).toContain("marker.style.setProperty('--marker-color', scoreColor(restaurant.scoreOutOfTen))")
    expect(browserMap).not.toContain('is-wanted')
    expect(browserCSS).not.toContain('.private-image-marker.is-wanted')
    expect(nativeMap).toContain('RestaurantScoreColorPolicy.color(forFivePointRating: rating)')
  })
})
